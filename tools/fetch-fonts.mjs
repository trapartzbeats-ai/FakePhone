// Downloads the app's Google Fonts (Anton, Inter, Roboto, Noto Color Emoji; all SIL OFL) into app/fonts
// and writes app/fonts/fonts.css, so the app (and the desktop build) renders the same with no internet.
// node tools/fetch-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'fonts');
const CSS_URL = 'https://fonts.googleapis.com/css2?family=Anton&family=Inter:wght@300;400;500;600;700;800&family=Roboto:wght@300;400;500;700&family=Noto+Color+Emoji&display=swap';
// a current Chrome user agent gets woff2 split by unicode-range
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36';

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
let css = await (await fetch(CSS_URL, { headers: { 'user-agent': UA } })).text();

const files = new Map();   // url -> local name
let family = '', subset = '';
for (const line of css.split('\n')) {
  const s = line.match(/^\/\* (.+) \*\/$/);
  if (s) subset = s[1].replace(/[^\w-]+/g, '-');
  const f = line.match(/font-family: '(.+)'/);
  if (f) family = f[1].replace(/\s+/g, '');
  const u = line.match(/url\((https:[^)]+)\)/);
  if (u && !files.has(u[1])) files.set(u[1], `${family}${subset ? '-' + subset : ''}-${files.size}.woff2`);
  if (u) subset = '';   // the emoji blocks have no subset comment
}
let bytes = 0;
for (const [url, name] of files) {
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  fs.writeFileSync(path.join(OUT, name), buf);
  bytes += buf.length;
}
for (const [url, name] of files) css = css.split(url).join(name);
fs.writeFileSync(path.join(OUT, 'fonts.css'), '/* Generated by tools/fetch-fonts.mjs from Google Fonts (SIL Open Font License). */\n' + css);
console.log(`${files.size} font files, ${(bytes / 1e6).toFixed(1)} MB -> ${OUT}`);
